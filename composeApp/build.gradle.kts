android {
    namespace = "io.github.kreader"
    compileSdk = libs.versions.android.compileSdk.get().toInt()

    defaultConfig {
        applicationId = "io.github.kreader"
        minSdk = libs.versions.android.minSdk.get().toInt()
        targetSdk = libs.versions.android.targetSdk.get().toInt()
        versionCode = 1
        versionName = "1.0.0"
    }

    splits {
        abi {
            isEnable = true
            reset()
            include("arm64-v8a", "armeabi-v7a", "x86_64")
            isUniversalApk = false
        }
    }

    packaging {
        resources {
            excludes += listOf(
                "/META-INF/{AL2.0,LGPL2.1}",
                "/META-INF/INDEX.LIST",
                "/META-INF/DEPENDENCIES"
            )
        }
    }

    signingConfigs {
        create("release") {
            val keystorePath = System.getenv("KEYSTORE_FILE")
            if (!keystorePath.isNullOrBlank() && file(keystorePath).exists()) {
                storeFile = file(keystorePath)
                storePassword = System.getenv("KEYSTORE_PASSWORD")
                keyAlias = System.getenv("KEY_ALIAS")
                keyPassword = System.getenv("KEY_PASSWORD")
            } else {
                // Fallback to debug keystore signing so release APKs can always be installed directly
                val debugConfig = signingConfigs.getByName("debug")
                initWith(debugConfig)
                val targetFile = debugConfig.storeFile
                if (targetFile != null && !targetFile.exists()) {
                    runCatching {
                        targetFile.parentFile?.mkdirs()
                        val pb = ProcessBuilder(
                            "keytool", "-genkeypair", "-v",
                            "-keystore", targetFile.absolutePath,
                            "-alias", debugConfig.keyAlias ?: "androiddebugkey",
                            "-keyalg", "RSA", "-keysize", "2048", "-validity", "10000",
                            "-storepass", debugConfig.storePassword ?: "android",
                            "-keypass", debugConfig.keyPassword ?: "android",
                            "-dname", "CN=Android Debug,O=Android,C=US"
                        )
                        pb.start().waitFor()
                    }
                }
            }
        }
    }

    buildTypes {
        getByName("release") {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            signingConfig = signingConfigs.getByName("release")
        }
        getByName("debug") {
            applicationIdSuffix = ".debug"
            isDebuggable = true
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
        isCoreLibraryDesugaringEnabled = true
    }
}

